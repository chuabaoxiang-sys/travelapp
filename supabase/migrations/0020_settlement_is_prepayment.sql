-- =====================================================================
-- 0020_settlement_is_prepayment.sql
-- 区分"聚合结算"里哪些是手动记的预付款、哪些是"结算建议"接受时生成的。
--
-- 背景：expense_id 为空的聚合结算有两种来源——(1) "结算建议"用最小转账数
-- 算法算出来的转账，很可能不对应A、B之间任何一笔真实账目（可能是A欠C、
-- C欠B，算法简化成A直接付B）；(2) 用户在"结算记录"旁"新增"手动记的一笔
-- （比如KN提前预付一大笔钱）。这两种都不挂 expense_id，但语义完全不同：
-- 预付款是A、B之间真实发生的钱，理应能在"按笔结算"里自动抵扣这两人之间
-- 后续产生的具体账目；结算建议算出来的转账不能这样用，会把不相关的钱错误
-- 核销到具体账目上——这正是当初把"按笔结算"和"结算建议"分成两条独立计算
-- 路径要规避的问题。加这个字段是为了让"按笔结算"的计算能只认预付款、
-- 不动结算建议那条路。
--
-- 纯新增、有默认值，不影响任何已有数据：老的结算记录全部是 false，
-- 含义跟改字段前完全一样（不参与"按笔结算"的自动抵扣）。
-- =====================================================================

alter table settlement
  add column is_prepayment boolean not null default false;

comment on column settlement.is_prepayment is
  '这笔聚合结算（expense_id为空）是不是用户手动记的预付款。true才会被"按笔结算"'
  '拿去自动抵扣这两人之间后续的具体账目；false（含"结算建议"接受时生成的）不参与'
  '自动抵扣，避免把不对应真实账目的简化转账错误核销到具体账目上。';
