-- =====================================================================
-- 0054_settlement_waived.sql
-- 结算「免了」：欠钱的人不用还，改由收钱的人自己承担
--
-- 【用户定下的规则（2026-11-10）】
-- - 真实情况：KN 按结算建议要还 BX RM53.58，BX 不要 KN 还，自己承担。
--   以前只能"去结算"，等于记成 KN 真的转了钱——KN 的「我的花费」多算、BX 的少算。
-- - 「免了」记成一条结算记录（from = 本来要还钱的人，to = 免掉的人），带 waived = true。
--   应用层算余额时，这种记录不算"已付/已收"，而是把这笔钱从 from 的应分摊挪到 to：
--   from 的应分摊 −amount，to 的应分摊 +amount。两人都两清，整趟花费不变。
-- - 金额默认整笔，可以只免一部分；跟普通结算记录一样可以改金额、删掉（= 撤回）。
-- - 只用于聚合结算（expense_id 为空、is_prepayment = false），不参与按笔结算/预付抵扣。
--
-- 【为什么加一列而不是新表】它就是一条结算记录，增删改、同步、按团队隔离都跟
-- settlement 完全一样；只差"钱有没有真的转"。新表反而要把整套 RLS、同步再抄一遍。
--
-- 【安全性】只加一列，默认 false：已有的结算记录全部照旧当"已付"算，不改任何数据。
-- =====================================================================

alter table settlement add column if not exists waived boolean not null default false;

comment on column settlement.waived is
  '结算「免了」（0054）：true = 收钱的人免掉了这笔，不算转账；应用层把金额从 from 的应分摊挪到 to';
