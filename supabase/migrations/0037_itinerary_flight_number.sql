-- 0037_itinerary_flight_number.sql
-- 行程项新增"航班号"：填了之后，卡片上会多一个可点的小标签，点一下跳去
-- FlightAware 免费查询页看实时状态。不接第三方付费API（历史航班记录、
-- 行李转盘信息都评估过，成本或数据source不划算），纯粹是"存个号码方便
-- 自己点出去查"，跟 booking_status/booking_deadline 同一个思路。
--
-- 【为什么直接加在 itinerary_item 上，不做"分类"系统】
-- 这张表目前没有任何"类型"概念——机票、酒店、活动全用同一套字段。航班号
-- 只是众多可选字段之一（跟 booking_status 一样，大部分行程项这里会是 null），
-- 不值得为了这一个字段引入分类体系，以后如果真需要分类再单独设计。
--
-- 【为什么不做格式校验】
-- 真实航班号写法很杂（国内代码有些两位数字、包夹货航代码等），业务上
-- 只是个跳转链接的拼接参数，不是需要校验的结构化数据，加 check 约束
-- 反而可能挡掉用户合法但不常见的写法。
-- =====================================================================

alter table itinerary_item add column if not exists flight_number text;

comment on column itinerary_item.flight_number is
  '可选的航班号，例如 CA981。填了之后App里会显示一个跳转到 FlightAware 查询页的按钮。'
  '不做格式校验，纯文本存储；null 表示这条行程项跟航班无关。';
