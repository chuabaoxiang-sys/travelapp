-- =====================================================================
-- 0044_allow_duplicate_rate_labels.sql
-- 汇率簿允许同一趟行程、同一币种下有同名的汇率。
--
-- 【为什么】
-- 0001 建库时加了 idx_rate_book_entry_trip_currency_label 这条唯一索引，原意是
-- "另存为新标签必须是不同名字"。实际用下来，用户会想给同一张卡（比如 "TNG VISA"）
-- 记好几次不同的汇率——每次刷卡的汇率都不一样，名字却天然就该一样。强行要求改名
-- （"TNG VISA 10/20"）只是给用户添麻烦。2026-10-20 用户决定放开。
--
-- 同名的汇率在界面上靠汇率数字区分：记账页的汇率按钮、汇率簿列表都是"名字 + 汇率"
-- 一起显示；代码里没有任何地方靠名字去找某一条汇率（都按 id），所以放开不影响任何
-- 已有逻辑。
--
-- 【顺序】
-- 必须先在数据库拿掉这条索引，再上线允许重名的前端——反过来的话，新版前端存下的
-- 同名汇率会被还没改的数据库拒收（23505），同步卡住（2026-10-06 CE 就是这么卡的）。
--
-- 【影响】只删一条索引，不改表结构、不动任何数据。要恢复就重新建这条唯一索引
-- （前提是到时候库里还没有同名的数据）。
-- =====================================================================

drop index if exists public.idx_rate_book_entry_trip_currency_label;
