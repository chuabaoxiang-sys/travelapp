-- 0030_day_satisfaction_rating_nullable.sql
-- 修正0029的一个设计问题：翻卡片"跳过"一张从没打过分的卡片时完全没有
-- 效果——pendingDaysForMember判断"待翻"的依据是"这行存不存在"，如果
-- "跳过"也是"不存在这一行"，那张卡会原地卡住，用户点跳过跟没点一样，
-- 这是本地真机测试流程里发现的真实bug，不是理论上的边界情况。
--
-- 改法：day_satisfaction.rating 允许为null，"跳过"变成"这一行存在，
-- 但rating是null"——用行的存在与否区分"问过没问过"（决定要不要出现在
-- 待翻队列），用rating是否为null区分"有没有具体表态"（决定算不算进
-- 心情曲线/多数决）。expense_satisfaction不受影响：账目那边没有"待翻
-- 队列"这个概念，"清除"就是直接删掉那一行，不需要留null行占位。
--
-- 安全性：单纯放宽一个列的约束（DROP NOT NULL），不涉及数据改写，
-- 不是bulk-update+DDL那种有坑的组合，风险很低。
-- =====================================================================

alter table day_satisfaction alter column rating drop not null;
