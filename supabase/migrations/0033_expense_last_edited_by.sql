-- 0033_expense_last_edited_by.sql
-- 账目的"最后修改人"——2026-09-08讨论定稿，详见docs/功能路线图-
-- 竞品借鉴版.md第2节第7条。出图对比过"轻量版（只加最后修改人）"和
-- "完整版（逐字段修改历史快照）"两种深度，用户选了轻量版：成本低，
-- 跟现有recordedBy（谁记的这笔账）是同一种展示方式，不需要额外的
-- 快照表，只是expense上加一列。
--
-- 只覆盖账目，不覆盖行程安排——这次讨论明确的范围：钱的事改动最敏感
-- （金额/谁付的/怎么分），行程安排改时间改地点相对没那么要紧。
--
-- 【为什么不记录"改了什么"】跟完整版比，轻量版故意不追踪具体哪个
-- 字段从什么改成什么——只需要知道"这笔账被改过、最后是谁改的"就够
-- 达到"变更归属"这个目的，不需要为了这个再引入一张快照表。
--
-- 安全性：单纯加一个可空列，没有bulk-update+DDL的坑，风险很低。
-- =====================================================================

alter table expense add column last_edited_by uuid references member (id) on delete set null;

comment on column expense.last_edited_by is
  '这笔账目最后一次编辑（不含创建）是谁做的——null表示从创建以来没被改过。'
  '只记录"谁"，不记录"改了什么"，是轻量版的变更归属，不是完整的修改历史快照。';
